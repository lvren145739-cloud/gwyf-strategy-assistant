const assert=require('node:assert/strict');
const V=require('../web/state.js');
const card=(rank,role='player',suit='spades')=>({rank,role,suit});
let s=V.blank();
const bj=[card('10'),card('6'),card('10','dealer')];
s=V.commit(s,bj);for(let i=0;i<10;i++)s=V.commit(s,bj);
assert.deepEqual(s.blackjack.used,Array(10).fill(0),'Repeated screenshots do not count as new cards');
s=V.commit(s,[...bj,card('7','dealer')]);s=V.archive(s);
assert.equal(s.blackjack.used.reduce((a,b)=>a+b,0),4,'Archive includes revealed dealer additions');
assert.equal(s.blackjack.used[9],2);assert.equal(s.blackjack.used[6],1);
assert.throws(()=>V.archive(s));
s=V.clone(s.undo.snapshot);assert.equal(s.blackjack.used.reduce((a,b)=>a+b,0),0);
assert.equal(s.blackjack.dealer.length,2);
assert.throws(()=>V.commit(s,[card('A'),card('A'),card('A'),card('A'),card('A','dealer')]),/单副/);
s.mode='poker';s=V.commit(s,['A','K','Q','J','2'].map(r=>card(r)));
const original=V.clone(s.poker.player);s=V.discard(s,15);
assert.deepEqual(s.poker.used,[V.cardId(original[4])],'Discard enters used immediately');
assert.equal(s.poker.player[4],null);
assert.throws(()=>V.commit(s,['A','K','Q','J','2'].map(r=>card(r))),/已用/);
assert.throws(()=>V.commit(s,['A','K','Q','10','3'].map(r=>card(r))),/保留/);
s=V.commit(s,['A','K','Q','J','3'].map(r=>card(r)));assert.equal(s.poker.used.length,1);
s=V.commit(s,['3','J','Q','K','A'].map(r=>card(r)));assert.equal(s.poker.used.length,1,'Recognition may reorder retained cards without losing their identity');
const used=V.clone(s.poker.used);s=V.commit(s,['A','K','Q','J','3'].map(r=>card(r)));assert.deepEqual(s.poker.used,used);
s=V.archive(s);assert.equal(s.poker.used.length,6,'Both discarded and final cards are recorded');
assert.throws(()=>V.archive(s));
const empty=V.resetDeck(s);assert.equal(empty.poker.used.length,0);assert.equal(empty.undo.snapshot.poker.used.length,6);
assert.throws(()=>V.commit({...V.blank(),mode:'poker'},Array(5).fill(card('A'))),/重复/);
const r=V.restore(JSON.parse(JSON.stringify(s)));assert.deepEqual(r.poker.used,s.poker.used);assert.equal(r.undo,null);
const invalid=V.restore({schema:1,blackjack:{player:[],dealer:[],used:[100,0,0,0,0,0,0,0,0,0]}});assert.deepEqual(invalid.blackjack.used,Array(10).fill(0));
console.log('Visible-card history: repeated capture, BJ dealer archive, caps, poker immediate discard, replacement, undo, save/restore passed.');
